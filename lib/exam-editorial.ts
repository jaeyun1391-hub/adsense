export function applyExamItemEditorial(item: InfoItem): InfoItem {
  const editorial = itemEditorial[item.slug as keyof typeof itemEditorial];
  if (!editorial) return item;
  return {
    ...item,
    updatedAt: reviewedAt,
    lastCheckedAt: reviewedAt,
    nextReviewAt,
    readingTime: "6분 읽기",
    audience: editorial.audience,
    keyChecks: editorial.keyChecks,
    sourceLinks: [{ label: item.source, url: item.sourceUrl }],
    details: { ...item.details, "편집 기준": "원문 공지와 접수 화면의 현재 조건을 대조" },
    body: [...item.body, ...editorial.body, ...itemVerificationBody(item, editorial)]
  };
}

