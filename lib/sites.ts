export const sites: SiteConfig[] = baseSites.map((site) => {
  const items = [...site.items, ...expandedItems[site.slug]];
  const guides = [...site.guides, ...expandedGuides[site.slug]];

  return {
    ...site,
    items,
    guides,
    stats: site.stats.map((stat, index) => {
      if (index === 0) return { ...stat, value: String(items.length) };
      if (index === 1) return { ...stat, value: String(guides.length) };
      return stat;
    })
  };
});

export const siteIcons = {
  Search,
  MapPin,
  ShieldCheck,
  Banknote,
  Sparkles
};

export function getSite(slug: string): SiteConfig | undefined {
  return sites.find((site) => site.slug === slug);
}

export function getSiteOrThrow(slug: string): SiteConfig {
  const site = getSite(slug);
  if (!site) {
    throw new Error(`Unknown site: ${slug}`);
  }
  return site;
}

export function getItem(site: SiteConfig, itemSlug: string): InfoItem | undefined {
  return site.items.find((item) => item.slug === itemSlug);
}

export function getGuide(site: SiteConfig, guideSlug: string): Guide | undefined {
  return site.guides.find((guideItem) => guideItem.slug === guideSlug);
}

export function siteStyle(site: SiteConfig): CSSProperties {
  return {
    "--accent": site.theme.accent,
    "--accent-2": site.theme.accent2,
    "--accent-weak": site.theme.weak,
    "--bg": site.theme.bg
  } as CSSProperties;
}
