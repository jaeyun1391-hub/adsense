const today = "2026-05-04";

function item(
  slug: string,
  title: string,
  summary: string,
  category: string,
  region: string,
  period: string,
  source: string,
  sourceUrl: string,
  tags: string[],
  details: Record<string, string>,
  body: string[],
  faq: { question: string; answer: string }[]
): InfoItem {
  return {
    slug,
    title,
    summary,
    category,
    region,
    period,
    source,
    sourceUrl,
    updatedAt: today,
    tags,
    details,
    body,
    faq
  };
}

function guide(slug: string, title: string, summary: string, category: string, body: string[]): Guide {
  return { slug, title, summary, category, updatedAt: today, body };
}

