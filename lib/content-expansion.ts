function textLength(blocks: string[]) {
  return blocks.join(" ").replace(/\s+/g, "").length;
}

function readingTimeFor(blocks: string[]) {
  const minutes = Math.max(4, Math.ceil(textLength(blocks) / 850));
  return `${minutes}분 읽기`;
}

function nextReviewDate(site: SiteSlug) {
  const date = new Date();
  date.setDate(date.getDate() + (site === "housing" ? 14 : 7));
  return date.toISOString().slice(0, 10);
}

