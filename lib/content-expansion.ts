export function enrichGuide(site: SiteSlug, guide: Guide): Guide {
  if (site === "business") {
    return enhanceBusinessGuide(guide);
  }

  const alreadyStructured = guide.body.some((block) => block.startsWith("## "));
  const seed: GuideSeed = {
    slug: guide.slug,
    title: guide.title,
    category: guide.category,
    focus: guide.summary.replace(/입니다\.$/, "")
  };
  const body = alreadyStructured ? guide.body : [...guideBody(site, seed), "## 추가 확인", ...guide.body];

  const enrichedBody = body.some((block) => block === "## 공식 출처 확인") ? body : [...body, ...guideDepthTail(site, guide.title)];

  if (site === "housing") {
    const deepBody = [...enrichedBody, ...housingDeepGuideBlocks(guide)];

    return {
      ...guide,
      summary: guide.summary,
      body: deepBody,
      thumbnail: housingThumbnail(guide.category),
      readingTime: readingTimeFor(deepBody),
      audience: housingAudience(guide.category),
      keyChecks: housingKeyChecks(guide.category, guide.summary),
      sourceLinks: housingSourceLinks("마이홈 주거복지", "https://www.myhome.go.kr/"),
      nextReviewAt: nextReviewDate(site)
    };
  }

  const deepBody = [...enrichedBody, ...nonHousingDeepGuideBlocks(site, guide), ...nonHousingGuideOperationalBlocks(site, guide)];

  return {
    ...guide,
    summary: guide.summary,
    body: deepBody,
    readingTime: readingTimeFor(deepBody),
    audience: nonHousingAudience(site, guide.category),
    keyChecks: nonHousingKeyChecks(site, guide.category, guide.summary),
    sourceLinks: nonHousingSourceLinks(site, site === "events" ? "문화포털" : "정부24", site === "events" ? "https://www.culture.go.kr/" : "https://www.gov.kr/"),
    nextReviewAt: nextReviewDate(site)
  };
}

