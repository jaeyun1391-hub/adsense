function detailCheckpoint(details: Record<string, string> | undefined, fallback: string) {
  if (!details) return fallback;
  return (
    details["준비 포인트"] ??
    details["방문 포인트"] ??
    details["이용 포인트"] ??
    details["확인 항목"] ??
    details["핵심 조건"] ??
    details["주의 사항"] ??
    fallback
  );
}

