function list(items: string[]) {
  return `- ${items.join("\n- ")}`;
}

function context(site: SiteConfig) {
  const experience = getExperience(site.slug);
  const profile = profiles[site.slug];
  return {
    experience,
    profile,
    categories: site.categories.join(" · "),
    examples: site.items.slice(0, 5).map((item) => item.title),
    sourceFocus: experience.sourceFocus,
    operator: `${publicOperator.name} · ${publicOperator.organization}`
  };
}

export function operatingProfile(site: SiteConfig) {
  return profiles[site.slug];
}

